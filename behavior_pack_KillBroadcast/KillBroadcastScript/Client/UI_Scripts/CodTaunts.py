def NormalizeCodTauntSource(source):
    source = str(source or COD_TAUNT_SOURCE_JIAHAO_CHARCOAL).strip().lower()
    validSources = [value for value, _ in COD_TAUNT_SOURCE_OPTIONS]
    if source not in validSources:
        return COD_TAUNT_SOURCE_JIAHAO_CHARCOAL
    return source


def GetCodTauntSourceName(source):
    source = NormalizeCodTauntSource(source)
    for value, name in COD_TAUNT_SOURCE_OPTIONS:
        if value == source:
            return name
    return u'嘉豪炭烧'


def GetCodTauntPool(source):
    source = NormalizeCodTauntSource(source)
    if source != COD_TAUNT_SOURCE_RANDOM:
        return COD_TAUNT_GROUPS.get(source, COD_TAUNT_GROUPS[COD_TAUNT_SOURCE_JIAHAO_CHARCOAL])
    return COD_TAUNT_RANDOM_POOL
